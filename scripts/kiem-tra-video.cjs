/* Run with Node's test runner and jsdom (or CT_VIDEO_TEST_JSDOM pointing to it). */
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require(process.env.CT_VIDEO_TEST_JSDOM || 'jsdom');
const root = path.resolve(__dirname, '..');
const player = fs.readFileSync(path.join(root, 'assets/can-ho-detail-video-override.js'), 'utf8');
const base = fs.readFileSync(path.join(root, 'assets/can-ho-detail-base.js'), 'utf8');
const preview = 'https://drive.google.com/file/d/1-F1kvnjO27gjjxOibGyz2iw91PDR2SzE/preview';
const second = 'https://drive.google.com/file/d/second_public_video/preview';
const src = '/video-can-ho/0123456789abcdef0123.mp4';
const media = { urls: [preview, second], code: 'CT.Stu.807', sources: { [preview]: { src }, [second]: { src: '/video-can-ho/abcdef0123456789abcd.mp4' } } };
function environment(width = 390, height = 760, html = '<button id="launch">Video</button>') {
  const dom = new JSDOM(html, { url: 'https://timthuesmartcity.com/can-ho/cho-thue-can-ho-studio-sakura-30m2-ct-stu-807/', runScripts: 'outside-only' });
  const w = dom.window;
  w.innerWidth = width; w.innerHeight = height; w.scrollY = 410; w.scrollX = 0;
  w.matchMedia = () => ({ matches: width <= 640, addEventListener() {}, removeEventListener() {} });
  w.visualViewport = new w.EventTarget();
  Object.assign(w.visualViewport, { height, width, offsetTop: 0 });
  w.scrollTo = (value) => { w.restoredScroll = value; };
  const timers = new Map(); let next = 0;
  w.setTimeout = (fn, ms) => { timers.set(++next, { fn, ms }); return next; };
  w.clearTimeout = (id) => timers.delete(id);
  w.HTMLMediaElement.prototype.play = function () { this.playCalls = (this.playCalls || 0) + 1; return Promise.resolve(); };
  w.HTMLMediaElement.prototype.pause = function () { this.pauseCalls = (this.pauseCalls || 0) + 1; };
  w.HTMLMediaElement.prototype.load = function () { this.loadCalls = (this.loadCalls || 0) + 1; };
  w.eval(player);
  return { dom, w, d: w.document, timers };
}
for (const [width, height] of [[390, 760], [844, 390], [1440, 900]]) {
  test(`one native player, viewport changes and complete close cleanup at ${width}x${height}`, () => {
    const { dom, w, d, timers } = environment(width, height);
    const launch = d.querySelector('#launch'); launch.focus();
    w.CTDetailVideo.open(media);
    const video = d.querySelector('video');
    assert.equal(d.querySelectorAll('video,iframe').length, 1);
    assert.equal(d.querySelector('iframe'), null);
    assert.ok(video.controls && video.playsInline);
    assert.equal(video.getAttribute('src'), src);
    assert.equal(video.playCalls, 1);
    assert.equal(d.querySelector('#ctVideoModal').style.height, height + 'px');
    w.visualViewport.height = height - 70;
    w.visualViewport.dispatchEvent(new w.Event('resize'));
    assert.equal(d.querySelector('#ctVideoModal').style.height, (height - 70) + 'px');
    video.dispatchEvent(new w.Event('loadeddata'));
    assert.ok(d.querySelector('.ct-video-status').hidden);
    assert.equal(timers.size, 0);
    d.querySelector('.ct-video-modal-close').click();
    assert.equal(d.querySelector('#ctVideoModal'), null);
    assert.equal(video.pauseCalls, 1);
    assert.equal(video.getAttribute('src'), null);
    assert.equal(video.loadCalls, 1);
    assert.equal(d.body.style.position, '');
    assert.equal(w.restoredScroll.top, 410);
    assert.equal(d.activeElement, launch);
    w.visualViewport.dispatchEvent(new w.Event('resize'));
    assert.equal(timers.size, 0);
    dom.window.close();
  });
}
test('video selection and retry stop the previous media; late events do not affect the next player', () => {
  const { dom, w, d, timers } = environment();
  w.CTDetailVideo.open(media);
  const first = d.querySelector('video');
  const select = d.querySelector('select'); select.value = '1'; select.dispatchEvent(new w.Event('change'));
  assert.equal(first.pauseCalls, 1);
  assert.equal(first.getAttribute('src'), null);
  assert.equal(d.querySelectorAll('video,iframe').length, 1);
  assert.match(d.querySelector('video').src, /abcdef0123456789abcd/);
  first.dispatchEvent(new w.Event('error'));
  assert.ok(d.querySelector('.ct-video-retry').hidden);
  d.querySelector('video').dispatchEvent(new w.Event('error'));
  assert.equal(d.querySelector('.ct-video-retry').hidden, false);
  assert.match(d.querySelector('.ct-video-status').textContent, /chưa tải được/);
  assert.equal(timers.size, 0);
  d.querySelector('.ct-video-retry').click();
  assert.equal(d.querySelectorAll('video,iframe').length, 1);
  assert.ok(d.querySelector('.ct-video-retry').hidden);
  d.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape' }));
  assert.equal(timers.size, 0);
  dom.window.close();
});
test('slow loads stay on the same player and expose recovery without an automatic Drive swap', () => {
  const { dom, w, d, timers } = environment();
  w.CTDetailVideo.open(media);
  const video = d.querySelector('video');
  for (const { fn } of [...timers.values()]) fn();
  assert.equal(d.querySelector('video'), video);
  assert.equal(d.querySelector('iframe'), null);
  assert.equal(d.querySelector('.ct-video-retry').hidden, false);
  video.dispatchEvent(new w.Event('canplay'));
  assert.ok(d.querySelector('.ct-video-status').hidden);
  d.querySelector('.ct-video-modal-close').click();
  dom.window.close();
});
test('new videos without an MP4 use only one fitted preview; unsafe media sources are rejected', () => {
  const { dom, w, d } = environment();
  w.CTDetailVideo.open({ urls: ['javascript:alert(1)'] });
  assert.equal(d.querySelector('#ctVideoModal'), null);
  w.CTDetailVideo.open({ urls: [preview], sources: { [preview]: { src: '//untrusted.example/video.mp4' } } });
  assert.equal(d.querySelector('video'), null);
  assert.equal(d.querySelectorAll('iframe').length, 1);
  assert.equal(d.querySelector('iframe').src, preview);
  const frame = d.querySelector('iframe');
  w.CTDetailVideo.open(media);
  assert.equal(frame.src, 'about:blank');
  assert.equal(d.querySelectorAll('#ctVideoModal').length, 1);
  assert.equal(d.querySelectorAll('video,iframe').length, 1);
  d.querySelector('.ct-video-modal-close').click();
  dom.window.close();
});
test('iOS autoplay rejection keeps usable native controls and clears loading', async () => {
  const { dom, w, d, timers } = environment();
  w.HTMLMediaElement.prototype.play = () => Promise.reject(Object.assign(new Error('gesture required'), { name: 'NotAllowedError' }));
  w.CTDetailVideo.open(media);
  await Promise.resolve();
  assert.ok(d.querySelector('.ct-video-status').hidden);
  assert.ok(d.querySelector('video').controls);
  assert.equal(d.querySelector('iframe'), null);
  assert.equal(timers.size, 0);
  d.querySelector('.ct-video-modal-close').click();
  dom.window.close();
});
test('the real apartment page reads the native manifest before stale Drive session cache', async () => {
  const html = fs.readFileSync(path.join(root, 'can-ho/cho-thue-can-ho-studio-sakura-30m2-ct-stu-807/index.html'), 'utf8');
  const { dom, w, d } = environment(1440, 900, html);
  w.sessionStorage.setItem('ct-detail-video-map-v2', JSON.stringify({ at: Date.now(), map: { 'CT.Stu.807': { videos: [second] } } }));
  w.fetch = async () => ({ ok: true, json: async () => ({ version: 1, items: { 'CT.Stu.807': { videos: [preview], sources: media.sources } } }) });
  w.eval(base);
  await new Promise(setImmediate);
  const launch = d.querySelector('.ct-video-launch');
  assert.ok(launch, 'video button appears from same-domain manifest');
  launch.click();
  assert.equal(d.querySelector('video').getAttribute('src'), src);
  assert.equal(d.querySelector('iframe'), null);
  assert.equal(d.querySelectorAll('script[src*="action=inventory"]').length, 0);
  d.querySelector('.ct-video-modal-close').click();
  dom.window.close();
});
test('late Apps Script response after timeout remains harmless', async () => {
  const html = fs.readFileSync(path.join(root, 'can-ho/cho-thue-can-ho-studio-sakura-30m2-ct-stu-807/index.html'), 'utf8');
  const { dom, w, d, timers } = environment(390, 760, html);
  w.fetch = async () => ({ ok: false });
  w.eval(base);
  await new Promise(setImmediate);
  const script = d.querySelector('script[src*="action=inventory"]');
  assert.ok(script);
  const callback = new URL(script.src).searchParams.get('callback');
  [...timers.values()].find(t => t.ms === 20000).fn();
  assert.equal(typeof w[callback], 'function');
  assert.doesNotThrow(() => w[callback]({ items: [] }));
  assert.equal(d.querySelector('.ct-video-launch'), null);
  dom.window.close();
});
